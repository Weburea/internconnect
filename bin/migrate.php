<?php

declare(strict_types=1);

/**
 * MySQL migrations (docs/59-mysql-migrations.md). Command line only; .htaccess never serves bin/.
 *
 *   php bin/migrate.php                       apply pending migrations to the MySQL database
 *   php bin/migrate.php --status              list applied / pending migrations
 *   php bin/migrate.php --database=name       use another database (default: DB_DATABASE when
 *                                             DB_CONNECTION=mysql, otherwise internconnect_db)
 *
 * Migrations live in database/migrations: *.sql (statements separated by ";" at line end) and
 * *.php (return a callable). Applied ones are recorded in the `migrations` table (Laravel layout:
 * id, migration, batch), so it works with the table that already exists in internconnect_db.
 * Everything is additive: CREATE TABLE IF NOT EXISTS / ADD COLUMN. Nothing is dropped.
 * After a run, database/migrations/mysql_schema_snapshot.sql is refreshed (SHOW CREATE TABLE of every
 * table) for importing on cPanel with phpMyAdmin.
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

$root = dirname(__DIR__);
require $root . '/vendor/autoload.php';
require_once $root . '/backend/Core/helpers.php';
\App\Core\Env::load($root);
chdir($root);
$_SERVER['SCRIPT_NAME'] = rtrim((string)parse_url(\App\Core\Env::get('APP_URL', ''), PHP_URL_PATH), '/') . '/index.php';
$_SERVER['HTTP_HOST'] = parse_url(\App\Core\Env::get('APP_URL', 'http://localhost'), PHP_URL_HOST) ?: 'localhost';

$opts = getopt('', ['status', 'database:']);
$database = $opts['database'] ?? (\App\Core\Env::get('DB_CONNECTION') === 'mysql' ? \App\Core\Env::get('DB_DATABASE') : 'internconnect_db');
if (!preg_match('/^[A-Za-z0-9_]+$/', (string)$database)) {
    fwrite(STDERR, "Invalid database name.\n");
    exit(2);
}
// Point the app's connection at MySQL for this process only.
$_ENV['DB_CONNECTION'] = 'mysql';
$_ENV['DB_DATABASE'] = $database;
$_ENV['DB_HOST'] = \App\Core\Env::get('DB_HOST', '127.0.0.1');
$_ENV['DB_PORT'] = \App\Core\Env::get('DB_PORT', '3306');
$_ENV['DB_USERNAME'] = \App\Core\Env::get('DB_USERNAME', 'root');
$_ENV['DB_PASSWORD'] = \App\Core\Env::get('DB_PASSWORD', '');

try {
    $pdo = new PDO('mysql:host=' . $_ENV['DB_HOST'] . ';port=' . $_ENV['DB_PORT'] . ';dbname=' . $database . ';charset=utf8mb4', $_ENV['DB_USERNAME'], $_ENV['DB_PASSWORD'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
} catch (Throwable $e) {
    fwrite(STDERR, 'Cannot connect to MySQL database "' . $database . '": ' . $e->getMessage() . "\n");
    exit(1);
}
$ref = new ReflectionProperty(\App\Core\Database::class, 'instance');
$ref->setAccessible(true);
$ref->setValue(null, $pdo);
$pdo->setAttribute(PDO::ATTR_DEFAULT_FETCH_MODE, PDO::FETCH_ASSOC);

$pdo->exec('CREATE TABLE IF NOT EXISTS migrations (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, migration VARCHAR(255) NOT NULL, batch INT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci');
$applied = $pdo->query('SELECT migration FROM migrations')->fetchAll(PDO::FETCH_COLUMN);
$files = glob($root . '/database/migrations/[0-9]*_*.{sql,php}', GLOB_BRACE) ?: [];
sort($files);
$pending = array_values(array_filter($files, static fn ($f) => !in_array(pathinfo($f, PATHINFO_FILENAME), $applied, true)));

echo "Database: {$database}\n";
if (isset($opts['status'])) {
    foreach ($files as $f) {
        $name = pathinfo($f, PATHINFO_FILENAME);
        echo (in_array($name, $applied, true) ? '  [applied] ' : '  [pending] ') . $name . "\n";
    }
    exit(0);
}
if (!$pending) {
    echo "Nothing to migrate.\n";
}
$batch = (int)$pdo->query('SELECT COALESCE(MAX(batch), 0) FROM migrations')->fetchColumn() + 1;
foreach ($pending as $file) {
    $name = pathinfo($file, PATHINFO_FILENAME);
    $t = microtime(true);
    try {
        if (str_ends_with($file, '.sql')) {
            $sql = preg_replace('/^\s*--.*$/m', '', (string)file_get_contents($file)) ?? '';
            foreach (preg_split('/;\s*$/m', $sql) ?: [] as $stmt) {
                if (trim($stmt) !== '') {
                    $pdo->exec($stmt);
                }
            }
            $detail = '';
        } else {
            $result = (require $file)();
            $detail = is_array($result) ? ' (' . implode(', ', $result) . ')' : '';
        }
        $pdo->prepare('INSERT INTO migrations (migration, batch) VALUES (?, ?)')->execute([$name, $batch]);
        printf("  migrated %s in %.2fs%s\n", $name, microtime(true) - $t, $detail);
    } catch (Throwable $e) {
        fwrite(STDERR, "  FAILED {$name}: " . $e->getMessage() . "\n");
        exit(1);
    }
}

// Snapshot of the full schema for cPanel / phpMyAdmin import.
$out = "-- InternConnect MySQL schema snapshot, generated by bin/migrate.php on " . date('Y-m-d H:i') . " from `{$database}`.\n"
    . "-- Import on a new server, then run php bin/migrate.php there to record the migrations.\n\nSET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS = 0;\n\n";
foreach ($pdo->query('SHOW TABLES')->fetchAll(PDO::FETCH_COLUMN) as $table) {
    $create = $pdo->query('SHOW CREATE TABLE `' . str_replace('`', '', $table) . '`')->fetch(PDO::FETCH_NUM)[1];
    $out .= preg_replace('/^CREATE TABLE/', 'CREATE TABLE IF NOT EXISTS', preg_replace('/ AUTO_INCREMENT=\d+/', '', $create)) . ";\n\n";
}
$out .= "SET FOREIGN_KEY_CHECKS = 1;\n";
file_put_contents($root . '/database/migrations/mysql_schema_snapshot.sql', $out);
echo "Schema snapshot: database/migrations/mysql_schema_snapshot.sql\n";
