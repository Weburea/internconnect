<?php

declare(strict_types=1);

namespace Tests\PHPUnit\Feature;

use App\Core\Router;

/**
 * Crawls every registered GET route (docs/45 section 1.4) and records the outcome in
 * docs/broken-links-audit.md. Fails on 404 / 5xx, PHP errors in the page, missing views,
 * and redirects that loop back to themselves. Routes with {params} use sample values.
 */
final class RouteCrawlerAuditTest extends HttpTestCase
{
    /** Sample values for dynamic segments. */
    private const SAMPLES = [
        'id' => '1', 'slug' => 'software-engineer-intern', 'kind' => 'resume', 'fileId' => '1', 'threadId' => '1',
    ];

    /** GET routes that must not be crawled (they change state, stream files or expect a gateway callback). */
    private const SKIP = [
        '/logout', '/admin/logout', '/payment/callback', '/elearning/go/{id}', '/elearning/logo/{id}',
        '/candidate/profile/resume', '/employer/candidates/{id}/files/{kind}', '/admin/document/stream',
        '/admin/interviews/{id}/files/{fileId}', '/employer/interviews/room/{id}/files/{fileId}', '/candidate/interview/room/{id}/files/{fileId}',
        '/employer/analytics/export/billing', '/employer/profile/logo', '/employer/profile/business-doc',
        // Receipts need a real Paystack reference of the signed-in account (404 otherwise, by design).
        '/candidate/billing/receipt/{id}', '/employer/billing/receipt/{id}',
        // Owner-only Jenny files and conversations: 404 for an id that is not yours, by design.
        '/jenny/files/{conversation}/{message}', '/candidate/ai-assistant/chats/{id}',
    ];

    /** Per-route sample paths where the generic samples do not exist. */
    private const ROUTE_SAMPLES = [
        '/api/v1/internships/{id}' => '/api/v1/internships/software-engineer-intern-nexura',
    ];

    public function testAuditAllRegisteredGetRoutes(): void
    {
        $router = new Router();
        require dirname(__DIR__, 3) . '/backend/routes.php';
        $routes = array_keys($router->getRegisteredRoutes()['GET'] ?? []);
        $this->assertNotEmpty($routes);

        $report = ['ok' => [], 'redirect' => [], 'fail' => [], 'skipped' => []];
        foreach ($routes as $route) {
            if (in_array($route, self::SKIP, true) || str_contains($route, '/export')) {
                $report['skipped'][] = $route;
                continue;
            }
            $path = self::ROUTE_SAMPLES[$route] ?? preg_replace_callback('/\{([a-zA-Z0-9_]+)\}/', static fn ($m) => self::SAMPLES[$m[1]] ?? '1', $route);
            $r = $this->request('GET', $path, null, ['Accept: text/html,application/json']);
            $problems = [];
            if ($r['status'] === 404 || $r['status'] >= 500 || $r['status'] === 0) {
                $problems[] = 'HTTP ' . $r['status'];
            }
            foreach (['Fatal error', 'Parse error', 'Warning: ', 'Notice: ', 'Deprecated: ', 'Uncaught ', 'View not found', 'Invalid controller action'] as $needle) {
                if (str_contains($r['body'], $needle)) {
                    $problems[] = 'page contains "' . trim($needle) . '"';
                }
            }
            if ($r['status'] >= 300 && $r['status'] < 400) {
                $target = (string)($r['headers']['location'] ?? '');
                if ($target !== '' && rtrim((string)parse_url($target, PHP_URL_PATH), '/') === rtrim(parse_url(static::$base . $path, PHP_URL_PATH), '/')) {
                    $problems[] = 'redirects to itself';
                }
                if (!$problems) {
                    $report['redirect'][] = [$route, $r['status'] . ' -> ' . $target];
                    continue;
                }
            }
            if ($problems) {
                $report['fail'][] = [$route, implode('; ', $problems)];
            } else {
                $report['ok'][] = [$route, (string)$r['status']];
            }
        }

        $this->writeReport($report, count($routes));
        $this->assertSame([], $report['fail'], "Broken routes:\n" . implode("\n", array_map(static fn ($f) => $f[0] . ' => ' . $f[1], $report['fail'])));
    }

    private function writeReport(array $report, int $total): void
    {
        $lines = ['# Route & Broken Link Audit', '', '> Generated by `tests/PHPUnit/Feature/RouteCrawlerAuditTest.php` on ' . date('Y-m-d H:i') . ' against ' . static::$base . '.', '',
            '| Result | Count |', '|---|---|',
            '| OK | ' . count($report['ok']) . ' |', '| Redirect | ' . count($report['redirect']) . ' |', '| Broken | ' . count($report['fail']) . ' |', '| Skipped (state-changing / file streams) | ' . count($report['skipped']) . ' |', '| **GET routes** | **' . $total . '** |', ''];
        if ($report['fail']) {
            $lines[] = '## Broken';
            $lines[] = '';
            foreach ($report['fail'] as [$route, $why]) {
                $lines[] = '- `' . $route . '`: ' . $why;
            }
            $lines[] = '';
        }
        $lines[] = '## Redirects';
        $lines[] = '';
        foreach ($report['redirect'] as [$route, $to]) {
            $lines[] = '- `' . $route . '`: ' . $to;
        }
        $lines[] = '';
        $lines[] = '## Skipped';
        $lines[] = '';
        $lines[] = implode(', ', array_map(static fn ($r) => '`' . $r . '`', $report['skipped']));
        $lines[] = '';
        file_put_contents(dirname(__DIR__, 3) . '/docs/broken-links-audit.md', implode("\n", $lines));
    }
}
